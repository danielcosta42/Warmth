"""Vendors of camp materials, from the QuestieDB of WoW: Forever, written to Core/VendorData.lua.

    python -I tools/gen-vendors.py [QuestieDB folder] [lodestar/tools folder]

The QuestieDB (the data addon Questie 12 requires; GPL-3.0) keeps, for every item, the NPCs that sell it, and for
every NPC its name, where it stands and which faction it is friendly to. This script takes the items a camp recipe
or a campfire kit asks for (by name, as the guides and the in-game recipes give them) and writes one line per
vendor. It reads the database with Lodestar's decoder (tools/questiedb.py there), so it is a build-time tool: the
output is committed and CI does not run this.

Fields by Questie's own indexes: item 1 = name, 14 = vendors; npc 1 = name, 7 = spawns {area = {{x, y}}},
13 = friendlyToFaction ("A", "H", "AH").
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
QUESTIEDB = sys.argv[1] if len(sys.argv) > 1 else r"E:\World of Warcraft\_forever_\Interface\AddOns\QuestieDB"
LODESTAR = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "..", "lodestar", "tools")
sys.path.insert(0, LODESTAR)
import questiedb  # noqa: E402

# What the camp recipes and the campfire kits take, by name. Whatever no vendor sells simply yields nothing.
MATERIALS = """Simple Wood, Star Wood, Thick Logs, Flint and Tinder,
Peacebloom, Empty Vial, Leaded Vial, Kingsblood, Swiftthistle, Crystal Vial, Dreamfoil,
Rough Stone, Copper Bar, Bronze Bar, Coarse Grinding Stone, Medium Leather, Thorium Bar, Rugged Leather,
Strange Dust, Vision Dust, Lesser Nether Essence, Large Brilliant Shard, Greater Eternal Essence,
Handful of Copper Bolts, Copper Tube, Whirring Bronze Gizmo, Bronze Tube, Heavy Leather, Thorium Widget,
Silverleaf, Arthas' Tears, Purple Lotus, Mountain Silversage, Runecloth,
Light Leather, Fine Thread, Rune Thread, Heavy Stone, Iron Ore, Silver Bar, Dense Stone, Truesilver Bar,
Slimy Murloc Scale, Iron Bar, Bolt of Linen Cloth, Coarse Thread, Bolt of Silk Cloth, Bolt of Runecloth,
Mystery Meat, Heavy Kodo Meat, Soothing Spices, Simple Flour, Refreshing Spring Water,
Linen Bandage, Anti-Venom, Mageweave Bandage, Strong Anti-Venom, Heavy Runecloth Bandage,
Raw Brilliant Smallfish, Raw Mithril Head Trout"""
WANTED = {name.strip() for name in MATERIALS.replace("\n", " ").split(",")}


def main():
    meta = questiedb.le_toc(os.path.join(QUESTIEDB, questiedb.TOC))
    raw = questiedb.entidades(meta)
    zones = questiedb.zonas(QUESTIEDB)
    items = {iid: row for iid, row in raw["Item"].items() if row.get(1) in WANTED and row.get(14)}
    vendors = {}  # npc -> [name, map, x, y, faction, set(items)]
    for iid, row in items.items():
        for npc in row[14].values():
            n = raw["Npc"].get(npc)
            if not n or not n.get(7):
                continue
            place = None
            for area, spots in sorted(n[7].items()):
                ui = zones.get(int(area), {}).get("uiMapId", 0)
                if ui and spots and " - Dungeon" not in zones[int(area)]["name"]:
                    first = spots[1]
                    place = (ui, int(round(first[1] * 100)), int(round(first[2] * 100)))
                    break
            if not place:
                continue
            v = vendors.setdefault(npc, [n.get(1, "?"), place[0], place[1], place[2], n.get(13, "AH"), set()])
            v[5].add(iid)
    lines = []
    for npc in sorted(vendors):
        name, ui, x, y, faction, sold = vendors[npc]
        lines.append('\t[%d] = { "%s", %d, %d, %d, "%s", { %s } },' % (
            npc, name.replace("\\", "\\\\").replace('"', '\\"'), ui, x, y, faction, ", ".join(str(i) for i in sorted(sold))))
    names = sorted((row[1], iid) for iid, row in items.items())
    out = [
        "--=============================================================================",
        "-- Vendors of camp materials: who sells what a camp recipe or a campfire kit asks for, and where they stand.",
        "--",
        "-- GENERATED by tools/gen-vendors.py from the QuestieDB of WoW: Forever, version %s. Do not edit by hand." % meta.get("Version", "?"),
        "-- The data is derived from QuestieDB (https://github.com/Questie/Questie), licensed under the GNU General",
        "-- Public License v3.0; this file is distributed under that licence. The rest of Warmth is MIT.",
        "--",
        "-- [npc id] = { name, uiMapID, x, y (0..10000), friendly to (\"A\", \"H\" or \"AH\"), { item ids } }",
        "-- %d vendors, %d items: %s." % (len(vendors), len(names), ", ".join(n for n, _ in names)),
        "--=============================================================================",
        "local _, W = ...",
        "",
        "W.VENDOR_DATA = {",
    ] + lines + ["}", ""]
    path = os.path.join(HERE, "..", "Core", "VendorData.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print("gen-vendors: %d vendors of %d items -> Core/VendorData.lua (%d bytes)" % (len(vendors), len(names), os.path.getsize(path)))
    xen = vendors.get(3400)
    print("check, Xen'to (measured in game at Orgrimmar 57.50, 53.14):", xen and xen[:5], sorted(xen[5]) if xen else None)
    for name, iid in names:
        print("  %-26s %7d  %d vendors" % (name, iid, sum(1 for v in vendors.values() if iid in v[5])))


if __name__ == "__main__":
    main()
