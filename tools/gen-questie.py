"""Where camp materials come from, out of the QuestieDB of WoW: Forever: Core/VendorData.lua (who sells them) and
Core/SourceData.lua (which zones have the most nodes of them, and which creatures drop them).

    python -I tools/gen-questie.py [QuestieDB folder] [lodestar/tools folder]

The QuestieDB (the data addon Questie 12 requires; GPL-3.0) keeps, for every item, the NPCs that sell it, the
objects that hold it and the creatures that drop it; and for every NPC and object, where it stands. This script
takes the items a camp recipe or a campfire kit asks for (by name, as the guides and the in-game recipes give
them), plus what those are made of one step back, and writes the two tables. It reads the database with
Lodestar's decoder (tools/questiedb.py there), so it is a build-time tool: the output is committed and CI does
not run this.

Fields by Questie's own indexes: item 1 = name, 2 = npcDrops, 3 = objectDrops, 14 = vendors; npc 1 = name,
4 and 5 = level, 7 = spawns {area = {{x, y}}}, 13 = friendlyToFaction ("A", "H", "AH"); object 4 = spawns.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
QUESTIEDB = sys.argv[1] if len(sys.argv) > 1 else r"E:\World of Warcraft\_forever_\Interface\AddOns\QuestieDB"
LODESTAR = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "..", "lodestar", "tools")
sys.path.insert(0, LODESTAR)
import questiedb  # noqa: E402

# What the camp recipes and the campfire kits take, by name. Whatever no vendor sells simply yields no vendor.
MATERIALS = """Simple Wood, Star Wood, Thick Logs, Flint and Tinder,
Peacebloom, Empty Vial, Leaded Vial, Kingsblood, Swiftthistle, Crystal Vial, Dreamfoil,
Rough Stone, Copper Bar, Bronze Bar, Coarse Grinding Stone, Medium Leather, Thorium Bar, Rugged Leather,
Strange Dust, Vision Dust, Lesser Nether Essence, Large Brilliant Shard, Greater Eternal Essence,
Handful of Copper Bolts, Copper Tube, Whirring Bronze Gizmo, Bronze Tube, Heavy Leather, Thorium Widget,
Silverleaf, Arthas' Tears, Purple Lotus, Mountain Silversage, Runecloth,
Light Leather, Fine Thread, Rune Thread, Heavy Stone, Iron Ore, Silver Bar, Dense Stone, Truesilver Bar,
Slimy Murloc Scale, Iron Bar, Bolt of Linen Cloth, Coarse Thread, Bolt of Silk Cloth, Bolt of Runecloth,
Mystery Meat, Heavy Kodo Meat, Soothing Spices, Simple Flour, Refreshing Spring Water,
Linen Bandage, Anti-Venom, Mageweave Bandage, Strong Anti-Venom, Heavy Runecloth Bandage,
Raw Brilliant Smallfish, Raw Mithril Head Trout"""
WANTED = {name.strip() for name in MATERIALS.replace("\n", " ").split(",")}
# What those are made of, one step back: an ore for a bar, a cloth for a bolt, a venom sac for an anti-venom.
RAW = {"Copper Ore", "Tin Ore", "Silver Ore", "Truesilver Ore", "Thorium Ore", "Coarse Stone", "Linen Cloth",
       "Silk Cloth", "Mageweave Cloth", "Wool Cloth", "Small Venom Sac", "Large Venom Sac", "Weak Flux"}
ZONES_PER_ITEM = 4

HEADER = [
    "-- GENERATED by tools/gen-questie.py from the QuestieDB of WoW: Forever, version %s. Do not edit by hand.",
    "-- The data is derived from QuestieDB (https://github.com/Questie/Questie), licensed under the GNU General",
    "-- Public License v3.0; this file is distributed under that licence. The rest of Warmth is MIT.",
]
RULE = "--" + "=" * 77


def write(name, lines):
    path = os.path.join(HERE, "..", "Core", name)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    return os.path.getsize(path)


def quoted(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def vendor_table(raw, zones, version):
    items = {iid: row for iid, row in raw["Item"].items() if row.get(1) in WANTED | RAW and row.get(14)}
    vendors = {}  # npc -> [name, map, x, y, faction, set(items)]
    for iid, row in items.items():
        for npc in row[14].values():
            n = raw["Npc"].get(npc)
            if not n or not n.get(7):
                continue
            place = None
            for area, spots in sorted(n[7].items()):
                ui = zones.get(int(area), {}).get("uiMapId", 0)
                if ui and spots and " - Dungeon" not in zones[int(area)]["name"]:
                    first = spots[1]
                    place = (ui, int(round(first[1] * 100)), int(round(first[2] * 100)))
                    break
            if not place:
                continue
            v = vendors.setdefault(npc, [n.get(1, "?"), place[0], place[1], place[2], n.get(13, "AH"), set()])
            v[5].add(iid)
    lines = []
    for npc in sorted(vendors):
        name, ui, x, y, faction, sold = vendors[npc]
        lines.append('\t[%d] = { "%s", %d, %d, %d, "%s", { %s } },' % (
            npc, quoted(name), ui, x, y, faction, ", ".join(str(i) for i in sorted(sold))))
    names = sorted((row[1], iid) for iid, row in items.items())
    size = write("VendorData.lua", [
        RULE,
        "-- Vendors of camp materials: who sells what a camp recipe or a campfire kit asks for, and where they stand.",
        "--",
        HEADER[0] % version, HEADER[1], HEADER[2],
        "--",
        "-- [npc id] = { name, uiMapID, x, y (0..10000), friendly to (\"A\", \"H\" or \"AH\"), { item ids } }",
        "-- %d vendors, %d items: %s." % (len(vendors), len(names), ", ".join(n for n, _ in names)),
        RULE,
        "local _, W = ...",
        "",
        "W.VENDOR_DATA = {",
    ] + lines + ["}", ""])
    print("gen-questie: %d vendors of %d items -> Core/VendorData.lua (%d bytes)" % (len(vendors), len(names), size))
    xen = vendors.get(3400)
    print("  check, Xen'to (measured in game at Orgrimmar 57.50, 53.14):", xen and xen[:5], sorted(xen[5]) if xen else None)


def source_table(raw, zones, version):
    """Per item, the zones with the most nodes that hold it and the zones with the most creatures that drop it
    (their levels and the commonest one's name). Dungeons are left out."""
    def open_zone(area):
        z = zones.get(int(area))
        return z["uiMapId"] if z and z["uiMapId"] and " - Dungeon" not in z["name"] else 0

    lines, listed = [], []
    for iid in sorted(raw["Item"]):
        row = raw["Item"][iid]
        if row.get(1) not in WANTED | RAW:
            continue
        nodes = {}
        for obj in (row.get(3) or {}).values():
            for area, spots in ((raw["Object"].get(obj) or {}).get(4) or {}).items():
                ui = open_zone(area)
                if ui:
                    nodes[ui] = nodes.get(ui, 0) + len(spots)
        mobs = {}  # uiMap -> [spawns, min level, max level, {name: spawns}]
        for npc in (row.get(2) or {}).values():
            n = raw["Npc"].get(npc) or {}
            for area, spots in (n.get(7) or {}).items():
                ui = open_zone(area)
                if not ui:
                    continue
                m = mobs.setdefault(ui, [0, 99, 0, {}])
                m[0] += len(spots)
                m[1], m[2] = min(m[1], n.get(4, 99)), max(m[2], n.get(5, n.get(4, 0)))
                m[3][n.get(1, "?")] = m[3].get(n.get(1, "?"), 0) + len(spots)
        if not nodes and not mobs:
            continue
        parts = []
        if nodes:
            top = sorted(nodes.items(), key=lambda kv: (-kv[1], kv[0]))[:ZONES_PER_ITEM]
            parts.append("n = { %s }" % ", ".join("{ %d, %d }" % kv for kv in top))
        if mobs:
            top = sorted(mobs.items(), key=lambda kv: (-kv[1][0], kv[0]))[:ZONES_PER_ITEM]
            parts.append("m = { %s }" % ", ".join('{ %d, %d, %d, %d, "%s" }' % (
                ui, m[0], m[1], m[2], quoted(max(sorted(m[3]), key=lambda k: m[3][k]))) for ui, m in top))
        lines.append("\t[%d] = { %s }, -- %s" % (iid, ", ".join(parts), row[1]))
        listed.append(row[1])
    size = write("SourceData.lua", [
        RULE,
        "-- Where camp materials are found in the world: the zones with the most nodes of each, and the creatures that",
        "-- drop it.",
        "--",
        HEADER[0] % version, HEADER[1], HEADER[2],
        "--",
        "-- [item id] = { n = { { uiMapID, nodes } }, m = { { uiMapID, spawns, min level, max level, commonest creature } } }",
        "-- Each list holds the %d zones with the most, most first; dungeons are left out." % ZONES_PER_ITEM,
        RULE,
        "local _, W = ...",
        "",
        "W.SOURCE_DATA = {",
    ] + lines + ["}", ""])
    print("gen-questie: %d items with a place in the world -> Core/SourceData.lua (%d bytes)" % (len(lines), size))
    print("  " + ", ".join(listed))


def main():
    meta = questiedb.le_toc(os.path.join(QUESTIEDB, questiedb.TOC))
    raw = questiedb.entidades(meta)
    zones = questiedb.zonas(QUESTIEDB)
    version = meta.get("Version", "?")
    vendor_table(raw, zones, version)
    source_table(raw, zones, version)
    missing = sorted((WANTED | RAW) - {row.get(1) for row in raw["Item"].values()})
    if missing:
        print("  not in the database by that name:", ", ".join(missing))


if __name__ == "__main__":
    main()
